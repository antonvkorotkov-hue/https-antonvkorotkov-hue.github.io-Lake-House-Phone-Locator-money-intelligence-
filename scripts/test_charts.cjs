const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const dom=new JSDOM('<!doctype html><body></body>',{runScripts:'outside-only'});
dom.window.eval(fs.readFileSync('charts.js','utf8'));
const {price,activity}=dom.window.LHCharts;
const t1='2026-10-19T20:00:00Z',t2='2026-10-19T21:00:00Z';
assert(!price({points:[{time:t1,value:null},{time:t2,value:''}]}).includes('<svg'),'Absent prices never become zero');
assert(!price({points:[{time:t1,value:101}],unit:'percent'}).includes('<svg'),'Invalid percentages rejected');
const one=price({points:[{time:t1,value:50}],unit:'percent',source:'Test Source'});
assert(one.includes('One verified observation'));assert(!one.includes('polyline'),'One point is not a trend');
const two=price({title:'Home moneyline',source:'Verified source',unit:'American odds',points:[{time:t2,value:-120},{time:t1,value:-100}],opening:{value:-110}});
for(const text of ['Home moneyline','Verified source','First observed','Latest observed','First observed → latest change','Source opening → latest change','Opening timestamp unknown','Connecting segments','observations and timestamps','-120'])assert(two.includes(text),text);
assert(two.includes('<polyline'),'Two distinct timestamps produce graph');
assert(two.includes('-20 American quote units'),'Observed quote-number delta is latest minus first');
assert(two.includes('Break-even probability:'),'American odds chart explains implied break-even probability');
assert(two.includes('not our prediction'),'Break-even probability is explicitly not the model forecast');
assert(two.includes('-10 American quote units'),'Source-opening delta is latest minus supplied opening');
assert(two.includes('not a linear change in implied probability'),'American quote changes are not implied probability changes');
const percentage=price({unit:'percent',points:[{time:t1,value:50},{time:t2,value:55}],opening:{value:40}});
assert(percentage.includes('+5 percentage points'));assert(percentage.includes('+15 percentage points'));
assert(!/NaN|undefined|Invalid Date/.test(two));
const duplicate=price({points:[{time:t1,value:10},{time:t1,value:20}],unit:'percent'});
assert(!duplicate.includes('polyline'),'Same timestamp values cannot create artificial movement');
assert(duplicate.includes('20%'),'Last same-time observation retained');
const missingActivity=activity({points:[{time:t1,premium:null,contracts:1}]});
assert(missingActivity.includes('Missing activity is not zero volume'));assert(!missingActivity.includes('<svg'));
const trades=activity({source:'Kalshi test fixture',points:[{time:t1,premium:10,contracts:20},{time:t2,premium:30,contracts:40}]});
for(const text of ['Sampled premium','Sampled contracts','not sportsbook dollar handle','No sampled observations','Kalshi test fixture'])assert(trades.includes(text),text);
assert.equal((trades.match(/<svg /g)||[]).length,2,'Premium and contract count are distinct graphs');
assert(trades.includes('$40'),'Premium sums observed transactions');
assert(!/NaN|undefined|Invalid Date/.test(trades));
assert(price({source:'<script>alert(1)</script>',points:[]}).includes('&lt;script&gt;'),'Source labels escaped');
dom.window.close();console.log('PASS: graph units/source/times/open/current/change, invalid/missing/duplicate observations, single-point fallback, chronological activity gaps, premium/contracts separation and escaping.');
